package controller

import (
	"net/http"
	"strconv"
	"valyria-backend/internal/apps/kubernetes/request"
	"valyria-backend/internal/apps/kubernetes/service"
	"valyria-backend/internal/pkg/ginhelper"

	"github.com/gin-gonic/gin"
	autoscalingv2 "k8s.io/api/autoscaling/v2"
)

type HPAController struct {
	hpa        service.HPAManager
	hpaHistory service.HpaHistoryManager
}

func NewHPAController(hpa service.HPAManager, hpaHistory service.HpaHistoryManager) *HPAController {
	return &HPAController{hpa: hpa, hpaHistory: hpaHistory}
}

func (c *HPAController) List(ctx *gin.Context) {
	idU, ok := ginhelper.RequireUintParam(ctx, "id")
	if !ok {
		return
	}
	id := idU
	ns := ctx.Param("namespace")
	data, err := c.hpa.List(impersonateCtx(ctx), id, ns)
	if err != nil {
		ctx.JSON(http.StatusOK, gin.H{"success": false, "code": -1, "msg": err.Error()})
		return
	}
	ctx.JSON(http.StatusOK, gin.H{"success": true, "code": 200, "data": data})
}

