// DeploymentController 定义控制器结构体
type DeploymentController struct {
	deployment service.DeploymentManager // 使用服务接口
}

// NewDeploymentController 创建新的 DeploymentsController 实例
func NewDeploymentController(deployment service.DeploymentManager) *DeploymentController {
	return &DeploymentController{deployment: deployment}
}

func (c *DeploymentController) List(ctx *gin.Context) {
	idU, ok := ginhelper.RequireUintParam(ctx, "id")
	if !ok {
		return
	}
	id := idU
	ns := ctx.Param("namespace")
	data, err := c.deployment.List(impersonateCtx(ctx), id, ns)
	if err != nil {
		ctx.JSON(http.StatusOK, gin.H{"success": false, "code": -1, "msg": err.Error()})
		return
	}
	ctx.JSON(http.StatusOK, gin.H{"success": true, "code": 200, "data": data})
}

